import { readFileSync, readdirSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { contentPathToSlug, markdownUrl } from './markdown-links.mjs';

const CONTENT_DIR = fileURLToPath(new URL('../src/content/docs/', import.meta.url));

/**
 * Reads a scalar frontmatter field written on one line (`key: value`, `key: "value"` or `key: 'value'`).
 *
 * @param {string} frontmatter
 * @param {string} key
 * @returns {string | undefined}
 */
function frontmatterField(frontmatter, key) {
  const match = new RegExp(`^${key}:[ \\t]*(.*)$`, 'm').exec(frontmatter);

  if (!match) {
    return undefined;
  }

  const raw = match[1].trim();

  if (raw.startsWith('"')) {
    return JSON.parse(raw.replace(/\\x([0-9a-fA-F]{2})/g, '\\u00$1'));
  }

  if (raw.startsWith("'")) {
    return raw.slice(1, -1).replace(/''/g, "'");
  }

  return raw;
}

/**
 * Returns the default-locale (English) pages by slug: `{ title, description, order }`, read from the frontmatter
 * (`order` is `sidebar.order`, or `undefined`).
 *
 * @param {string[]} localeKeys Locale directory names to skip (every locale except `root`).
 * @returns {Map<string, { title: string, description: string, order: number | undefined }>}
 */
export function englishPages(localeKeys) {
  const pages = new Map();
  const walk = (dir) => {
    for (const name of readdirSync(dir)) {
      const file = path.join(dir, name);
      const relative = path.relative(CONTENT_DIR, file).split(path.sep).join('/');

      if (statSync(file).isDirectory()) {
        if (!localeKeys.includes(relative)) {
          walk(file);
        }
        continue;
      }

      if (!/\.mdx?$/.test(name) || name.startsWith('_')) {
        continue;
      }

      const frontmatter = /^---\r?\n([\s\S]*?)\r?\n---/.exec(readFileSync(file, 'utf8'))?.[1] ?? '';
      const title = frontmatterField(frontmatter, 'title');

      if (!title) {
        throw new Error(`${relative} has no title.`);
      }

      const description = frontmatterField(frontmatter, 'description') ?? '';
      const order = /^sidebar:[ \t]*\r?\n(?:[ \t]+.*\r?\n)*?[ \t]+order:[ \t]*(-?\d+)/m.exec(`${frontmatter}\n`)?.[1];

      pages.set(contentPathToSlug(relative), {
        title,
        description,
        order: order === undefined ? undefined : Number(order),
      });
    }
  };

  walk(CONTENT_DIR);

  return pages;
}

/**
 * Returns the slugs of an `autogenerate` directory: its English pages sorted like Starlight does, by `sidebar.order`
 * (pages without one last) and then by slug.
 *
 * @param {string} directory
 * @param {Map<string, { order?: number }>} pages
 */
function autogeneratedSlugs(directory, pages) {
  const prefix = `${directory}/`;
  const rank = (slug) => pages.get(slug)?.order ?? Number.POSITIVE_INFINITY;

  return [...pages.keys()].filter((slug) => slug.startsWith(prefix) || slug === directory)
    .sort((a, b) => rank(a) - rank(b) || (a < b ? -1 : a > b ? 1 : 0));
}

/**
 * Returns the sidebar groups as `{ label, slugs, sections }`: `slugs` lists every page of the top-level group in
 * sidebar order (nested groups flattened, `autogenerate` directories expanded to their English pages); `sections`
 * lists the nested groups (`{ label, slugs }`), empty for flat groups.
 *
 * @param {Array<{ label: string, items: Array<object> }>} sidebar
 * @param {Map<string, { order?: number }>} pages Result of {@link englishPages}.
 */
export function sidebarGroups(sidebar, pages) {
  const expand = (item, group) => {
    if (item.slug !== undefined) {
      return [item.slug];
    }

    if (item.autogenerate) {
      return autogeneratedSlugs(item.autogenerate.directory, pages);
    }

    if (Array.isArray(item.items)) {
      return item.items.flatMap((child) => expand(child, group));
    }

    throw new Error(`Unsupported sidebar item in group "${group}".`);
  };

  return sidebar.map((group) => ({
    label: group.label,
    slugs: group.items.flatMap((item) => expand(item, group.label)),
    sections: group.items.filter((item) => item.label !== undefined && item.slug === undefined)
      .map((item) => ({ label: item.label, slugs: expand(item, group.label) })),
  }));
}

/**
 * Builds the `details` section of `llms.txt`: one Markdown list per sidebar group, each line linking a page's
 * Markdown URL with its one-line description; nested groups become H3 subsections. Pages missing from the sidebar are
 * listed first under "Overview".
 *
 * @param {ReturnType<typeof sidebarGroups>} groups
 * @param {Map<string, { title: string, description: string }>} pages
 * @param {{ site: string, base: string, intro: string }} options
 */
export function llmsTxtDetails(groups, pages, { site, base, intro }) {
  const listed = new Set(groups.flatMap((group) => group.slugs));
  const unlisted = [...pages.keys()].filter((slug) => !listed.has(slug)).sort();
  const sections = [intro];
  const line = (slug) => {
    const page = pages.get(slug);

    if (!page) {
      throw new Error(`Sidebar slug "${slug}" has no English page.`);
    }

    const url = new URL(markdownUrl(slug, base), site).href;

    return `- [${page.title}](${url})${page.description ? `: ${page.description}` : ''}`;
  };

  for (const { label, slugs, sections: nested = [] } of [{ label: 'Overview', slugs: unlisted }, ...groups]) {
    if (slugs.length === 0) {
      continue;
    }

    if (nested.length === 0) {
      sections.push(`## ${label}\n\n${slugs.map(line).join('\n')}`);
      continue;
    }

    // Nested groups (one per extension package) become H3 subsections; pages outside them stay under the H2.
    const inNested = new Set(nested.flatMap((section) => section.slugs));
    const direct = slugs.filter((slug) => !inNested.has(slug));
    const parts = [`## ${label}`];

    if (direct.length > 0) {
      parts.push(direct.map(line).join('\n'));
    }

    for (const section of nested) {
      parts.push(`### ${section.label}\n\n${section.slugs.map(line).join('\n')}`);
    }

    sections.push(parts.join('\n\n'));
  }

  return sections.join('\n\n');
}
