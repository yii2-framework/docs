/**
 * Returns the "Extensions" sidebar group: one sub-group per package of `packages.json` whose guides were synced into
 * `src/content/docs/extensions/<name>/` by `scripts/sync.mjs` (run by `npm run build` through `prebuild`), with the
 * guide pages and a "Reference" sub-group generated by `tools/bin/reference`. Packages without pages (not synced
 * yet, or skipped by the sync) are left out with a warning, so the sidebar and `llms.txt` never point to a missing
 * directory and `astro dev` works without a sync.
 */
function extensionsGroup() {
  /** @type {Array<{ name: string, title: string, type?: string }>} */
  const packages = JSON.parse(
    readFileSync(new URL("./packages.json", import.meta.url), "utf8"),
  ).filter(({ type }) => type !== "framework");
  const synced = packages.filter(({ name }) => {
    const found = existsSync(
      new URL(
        `./src/content/docs/extensions/${name}/index.md`,
        import.meta.url,
      ),
    );

    if (!found) {
      console.warn(
        `[extensions] ${name} has no synced pages (not synced yet, or skipped by scripts/sync.mjs); ` +
          "the sidebar omits it. Run `npm run sync` or `npm run sync:local`.",
      );
    }

    return found;
  });

  return synced.length === 0
    ? []
    : [
        {
          label: "Extensions",
          items: synced.map(({ name, title }) => ({
            label: title,
            items: extensionItems(pages, name),
          })),
        },
      ];
}

// Tools have guides and skills, but no Composer package or PHP API reference.
function developmentToolsGroup() {
  const tools = JSON.parse(
    readFileSync(new URL("./tools.json", import.meta.url), "utf8"),
  );
  const synced = tools.filter(({ name }) =>
    existsSync(
      new URL(
        `./src/content/docs/development-tools/${name}/index.md`,
        import.meta.url,
      ),
    ),
  );
  return synced.length === 0
    ? []
    : [
        {
          label: "Development tools",
          items: synced.map(({ name, title }) => ({
            label: title,
            items: [
              {
                autogenerate: {
                  directory: `development-tools/${name}`,
                },
              },
            ],
          })),
        },
      ];
}

